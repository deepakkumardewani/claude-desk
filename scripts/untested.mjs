#!/usr/bin/env node
// Enumerates untested source files per package and writes the coverage inventory.
// Run after: vp run -r test (coverageBase emits json-summary), or per package: vp test run --coverage
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const OUTPUT_FILE = join(ROOT, "agent_docs", "QUALITY-COVERAGE-INVENTORY.md");

const PACKAGES = [
  { name: "claude-desk", dir: "apps/cli" },
  { name: "web", dir: "apps/web" },
  { name: "schema", dir: "packages/schema" },
];

// Mirrors spec section 4 (and COVERAGE_EXCLUDE in vitest.shared.ts); paths are relative to the package root.
const EXCLUDE_PATTERNS = [
  /\.test\.tsx?$/,
  /(^|\/)__fixtures__\//,
  /^src\/usage\/fixtures\.ts$/,
  /^src\/testing\//,
  /\.d\.ts$/,
  /^src\/main\.tsx$/,
  /^src\/(bin|main)\.ts$/,
  /^scripts\//,
  /\.config\.ts$/,
];

const SOURCE_PATTERN = /\.tsx?$/;

function walk(dir) {
  return readdirSync(dir, { withFileTypes: true }).flatMap((entry) => {
    const full = join(dir, entry.name);
    if (entry.isDirectory()) return walk(full);
    return [full];
  });
}

function listSourceFiles(pkgRoot) {
  const srcDir = join(pkgRoot, "src");
  if (!existsSync(srcDir)) return [];
  return walk(srcDir)
    .map((file) => relative(pkgRoot, file))
    .filter((file) => SOURCE_PATTERN.test(file))
    .filter((file) => !EXCLUDE_PATTERNS.some((pattern) => pattern.test(file)))
    .sort();
}

function loadSummary(pkgRoot) {
  const summaryPath = join(pkgRoot, "coverage", "coverage-summary.json");
  if (!existsSync(summaryPath)) return null;
  const summary = JSON.parse(readFileSync(summaryPath, "utf8"));
  const byFile = new Map();
  for (const [file, metrics] of Object.entries(summary)) {
    if (file === "total") continue;
    byFile.set(relative(pkgRoot, file), metrics.lines);
  }
  return byFile;
}

function siblingTestExists(pkgRoot, file) {
  const base = file.replace(SOURCE_PATTERN, "");
  return [".test.ts", ".test.tsx"].some((ext) => existsSync(join(pkgRoot, base + ext)));
}

function buildRows(pkgRoot, files, summary) {
  return files
    .map((file) => {
      const lines = summary?.get(file);
      return {
        file,
        pct: lines ? lines.pct : 0,
        covered: lines ? lines.covered : 0,
        total: lines ? lines.total : 0,
        zero: !lines || lines.covered === 0,
        noTest: !siblingTestExists(pkgRoot, file),
      };
    })
    .sort((a, b) => a.pct - b.pct || a.file.localeCompare(b.file));
}

function renderPackage({ name, dir }, rows, hasSummary) {
  const flagged = rows.filter((row) => row.zero || row.noTest);
  const out = [`## ${name} (\`${dir}\`)`, ""];
  if (!hasSummary)
    out.push(
      "> No `coverage/coverage-summary.json` found; run coverage first. Line data below is zeroed.",
      "",
    );
  out.push(
    `In-scope files: ${rows.length}; zero-coverage: ${rows.filter((r) => r.zero).length}; no sibling test: ${rows.filter((r) => r.noTest).length}`,
    "",
  );
  if (flagged.length === 0) return [...out, "No flagged files.", ""];
  out.push(
    "| File | Lines % | Covered/Total | 0 covered | No sibling test |",
    "|---|---|---|---|---|",
  );
  for (const r of flagged) {
    out.push(
      `| \`${r.file}\` | ${r.pct} | ${r.covered}/${r.total} | ${r.zero ? "yes" : ""} | ${r.noTest ? "yes" : ""} |`,
    );
  }
  return [...out, ""];
}

function main() {
  const sections = PACKAGES.map((pkg) => {
    const pkgRoot = join(ROOT, pkg.dir);
    const summary = loadSummary(pkgRoot);
    const rows = buildRows(pkgRoot, listSourceFiles(pkgRoot), summary);
    return renderPackage(pkg, rows, summary !== null);
  });
  const report = [
    "# Quality coverage inventory",
    "",
    "Generated by `scripts/untested.mjs`; do not edit by hand.",
    "",
    ...sections.flat(),
  ].join("\n");
  writeFileSync(OUTPUT_FILE, report);
  console.log(report);
}

main();
